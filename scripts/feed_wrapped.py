#!/usr/bin/env python3
"""
feed_wrapped.py — Feeds Medallion Lakehouse Gold data directly to Mixtape_Wrapped_storyboard.html

Usage:
  Interactive Mode:
    python scripts/feed_wrapped.py

  Direct CLI Mode:
    python scripts/feed_wrapped.py --user user_real_01 --year 2026
    python scripts/feed_wrapped.py --user user_real_02 --year 2025 --no-open
    python scripts/feed_wrapped.py --list
    python scripts/feed_wrapped.py --serve --port 8080

Options:
  -u, --user USER_ID     User ID to feed (e.g. user_real_01, user_synth_004)
  -y, --year YEAR        Year to load (e.g. 2026, 2025, 2024)
  -l, --list             List all available users and years in the Gold layer
  -r, --rebuild          Run local_gold_build.py first to refresh Gold tables
  -n, --no-open          Update HTML without automatically launching browser
  -s, --serve            Serve storyboard via local HTTP server
  -p, --port PORT        Port for local HTTP server (default: 8080)
"""

import argparse
import http.server
import json
import os
import re
import socketserver
import subprocess
import sys
import threading
import time
import webbrowser
from pathlib import Path

# Safe Windows stdout encoding
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# Paths
REPO_ROOT = Path(__file__).resolve().parent.parent
HTML_FILE = REPO_ROOT / "Mixtape_Wrapped_storyboard.html"
GOLD_DIR = REPO_ROOT / "gold_export"
PAYLOAD_CSV = GOLD_DIR / "wrapped_payload.csv"
JSON_DIR = GOLD_DIR / "wrapped_json"
BUNDLE_JS = GOLD_DIR / "wrapped_bundle.js"
SEGMENTS_JSON = REPO_ROOT / "output" / "validation" / "user_segments.json"


def ensure_gold_exists(rebuild=False):
    """Checks if Gold exports exist; rebuilds if missing or requested."""
    needs_build = rebuild or not PAYLOAD_CSV.exists() or not JSON_DIR.exists()
    if needs_build:
        print("[*] Building Gold marts from landing data...")
        script = REPO_ROOT / "scripts" / "local_gold_build.py"
        cmd = [sys.executable, str(script), "--landing", str(REPO_ROOT / "output"), "--out", str(GOLD_DIR)]
        res = subprocess.run(cmd, cwd=REPO_ROOT)
        if res.returncode != 0:
            print(f"[!] Error: Gold build failed with code {res.returncode}")
            sys.exit(1)


def load_wrapped_catalog():
    """Loads all wrapped payloads and user metadata."""
    ensure_gold_exists()

    catalog = {}
    users_meta = []

    # Try reading wrapped_payload.csv first
    if PAYLOAD_CSV.exists():
        import pandas as pd
        df = pd.read_csv(PAYLOAD_CSV)
        for r in df.itertuples():
            uid = str(r.user_id).strip()
            yr = int(r.year)
            if uid not in catalog:
                catalog[uid] = {}
            try:
                catalog[uid][yr] = json.loads(r.payload_json)
            except Exception:
                pass
    else:
        # Fallback to reading JSON files
        for p in JSON_DIR.glob("*_*.json"):
            name = p.stem
            parts = name.rsplit("_", 1)
            if len(parts) == 2 and parts[1].isdigit():
                uid, yr = parts[0], int(parts[1])
                if uid not in catalog:
                    catalog[uid] = {}
                try:
                    catalog[uid][yr] = json.loads(p.read_text(encoding="utf-8"))
                except Exception:
                    pass

    # Load segment info for friendly genre labels
    segments = {}
    if SEGMENTS_JSON.exists():
        try:
            for s in json.loads(SEGMENTS_JSON.read_text(encoding="utf-8")):
                segments[s["user_id"]] = s
        except Exception:
            pass

    for uid, yrs in catalog.items():
        is_real = "real" in uid
        seg = segments.get(uid, {})
        genres = seg.get("favorite_genres", [])
        if not genres and yrs:
            # Fallback: check genres in the latest payload
            latest_yr = max(yrs.keys())
            payload_genres = yrs[latest_yr].get("genres", [])
            genres = [g["name"] for g in payload_genres[:3]]
        genre_str = ", ".join(genres[:3]).title() if genres else ""
        label = f"{uid}" + (f" ({genre_str})" if genre_str else "")
        users_meta.append({
            "user_id": uid,
            "is_real": is_real,
            "label": label,
            "years": sorted(list(yrs.keys()))
        })

    users_meta.sort(key=lambda x: (not x["is_real"], x["user_id"]))
    return catalog, users_meta


def update_bundle_js(catalog, users_meta):
    """Writes the full catalog and user list into gold_export/wrapped_bundle.js."""
    GOLD_DIR.mkdir(parents=True, exist_ok=True)
    bundle_content = (
        "// Auto-generated by Medallion Pipeline Gold Layer\n"
        f"window.WRAPPED_USERS = {json.dumps(users_meta, indent=2)};\n"
        f"window.WRAPPED_CATALOG = {json.dumps(catalog)};\n"
    )
    BUNDLE_JS.write_text(bundle_content, encoding="utf-8")


def feed_to_html(user_id, year, payload):
    """Directly updates Mixtape_Wrapped_storyboard.html with the selected user & year payload."""
    if not HTML_FILE.exists():
        print(f"[!] Error: {HTML_FILE} not found!")
        sys.exit(1)

    html_content = HTML_FILE.read_text(encoding="utf-8")

    # Ensure gold_export/wrapped_bundle.js is referenced in head
    bundle_tag = '<script src="gold_export/wrapped_bundle.js"></script>'
    if 'wrapped_bundle.js' not in html_content:
        html_content = re.sub(
            r'(</head>)',
            f'  {bundle_tag}\n\\1',
            html_content,
            count=1,
            flags=re.IGNORECASE
        )

    # Clean payload string
    payload_str = json.dumps(payload, separators=(',', ':'))

    replacement_block = (
        "/* WRAPPED_DATA_START */\n"
        f"var ACTIVE_USER = \"{user_id}\";\n"
        f"var ACTIVE_YEAR = {year};\n"
        f"var REAL = {payload_str};\n"
        "/* WRAPPED_DATA_END */"
    )

    start_tag = "/* WRAPPED_DATA_START */"
    end_tag = "/* WRAPPED_DATA_END */"
    if start_tag in html_content and end_tag in html_content:
        idx_start = html_content.find(start_tag)
        idx_end = html_content.find(end_tag) + len(end_tag)
        html_content = html_content[:idx_start] + replacement_block + html_content[idx_end:]
    else:
        pattern = r'var\s+REAL\s*=\s*\{[\s\S]*?\}\s*,\s*D\s*=\s*REAL\s*,'
        html_content = re.sub(
            pattern,
            lambda _: f'{replacement_block}\nvar D = REAL,',
            html_content,
            count=1
        )

    HTML_FILE.write_text(html_content, encoding="utf-8")


def print_banner(user_id, year, payload, meta_label):
    """Prints an ASCII summary of the loaded Wrapped tape."""
    mins = payload.get("minutes", 0)
    full_days = round(mins / 1440, 1)
    act_days = payload.get("days", payload.get("act", 0))
    plays = payload.get("plays", 0)
    streak = payload.get("streak", {})
    streak_len = streak.get("len", 0) if streak else 0
    big = payload.get("big", {})
    artists = payload.get("artists", [])
    top_artist = artists[0]["name"] if artists else "Unknown"
    top_artist_plays = artists[0].get("plays", 0) if artists else 0
    top_artist_mins = artists[0].get("mins", 0) if artists else 0
    tracks = payload.get("tracks", [])
    top_track = tracks[0]["title"] if tracks else "Unknown"
    top_track_artist = tracks[0].get("artist", "") if tracks else ""
    skip = payload.get("skip", {})
    skip_pct = skip.get("pct", 0)
    genres = payload.get("genres", [])
    genres_str = " · ".join(f"{g['name']} ({g['pct']}%)" for g in genres[:3]) if genres else "N/A"

    print("\n" + "=" * 70)
    print("   📼  SPOTIFY MEDALLION LAKEHOUSE — WRAPPED MIXTAPE FEEDER  📼")
    print("=" * 70)
    print(f"  Listener:       {meta_label}")
    print(f"  Mixtape Year:   {year}")
    print(f"  Target File:    {HTML_FILE.name}")
    print("-" * 70)
    print(f"  • Total Time:   {mins:,} minutes ({full_days} full days) across {act_days} active days")
    print(f"  • Total Plays:  {plays:,} songs played")
    print(f"  • #1 Artist:    {top_artist} ({top_artist_plays:,} plays · {top_artist_mins:,} min)")
    print(f"  • #1 Song:      \"{top_track}\" by {top_track_artist}")
    if streak_len:
        print(f"  • Streak:       {streak_len} days in a row without missing a beat")
    if big:
        print(f"  • Biggest Day:  {big.get('mins', 0):,} minutes ({big.get('plays', 0)} plays)")
    print(f"  • Skip Rate:    {skip_pct}%")
    print(f"  • Top Genres:   {genres_str}")
    print("=" * 70)


def serve_and_open(user_id, year, port=8080):
    """Starts a local HTTP server and opens the browser."""
    os.chdir(str(REPO_ROOT))
    handler = http.server.SimpleHTTPRequestHandler

    class QuietServer(socketserver.TCPServer):
        allow_reuse_address = True

    try:
        httpd = QuietServer(("", port), handler)
    except OSError:
        port = port + 1
        httpd = QuietServer(("", port), handler)

    url = f"http://localhost:{port}/Mixtape_Wrapped_storyboard.html?user={user_id}&year={year}"
    print(f"\n[*] Serving at http://localhost:{port}/")
    print(f"[>] Launching browser: {url}\n")

    t = threading.Thread(target=httpd.serve_forever, daemon=True)
    t.start()
    webbrowser.open(url)

    try:
        print("Press Ctrl+C to stop the server.")
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        print("\n[*] Server stopped.")


def interactive_select(users_meta):
    """Interactive CLI menu to choose user and year."""
    real_users = [u for u in users_meta if u["is_real"]]
    synth_users = [u for u in users_meta if not u["is_real"]]

    print("\n" + "=" * 65)
    print("   📼  SELECT LISTENER PERSONA & YEAR")
    print("=" * 65)
    print(" Real Listeners (Exports & Live API):")
    idx = 1
    selection_map = {}
    for u in real_users:
        yrs_str = ", ".join(str(y) for y in u["years"])
        print(f"   [{idx:2d}] {u['label']:<40} [Years: {yrs_str}]")
        selection_map[idx] = u
        idx += 1

    print("\n Synthetic Personas (Lakehouse Generated & Calibrated):")
    sample_synths = synth_users[:5]
    for u in sample_synths:
        yrs_str = ", ".join(str(y) for y in u["years"])
        print(f"   [{idx:2d}] {u['label']:<40} [Years: {yrs_str}]")
        selection_map[idx] = u
        idx += 1
    if len(synth_users) > 5:
        print(f"   ... ({len(synth_users) - 5} additional synthetic users available: user_synth_005 to user_synth_044)")

    print("-" * 65)
    prompt = f"Select number [1-{idx-1}] or type user_id [default: 1]: "
    choice = input(prompt).strip()

    chosen_user = None
    if not choice:
        chosen_user = selection_map[1]
    elif choice.isdigit() and int(choice) in selection_map:
        chosen_user = selection_map[int(choice)]
    else:
        # Match by ID
        matches = [u for u in users_meta if u["user_id"].lower() == choice.lower()]
        if matches:
            chosen_user = matches[0]
        else:
            print(f"[!] Unknown user '{choice}'. Defaulting to user_real_01.")
            chosen_user = selection_map[1]

    avail_years = chosen_user["years"]
    latest_year = max(avail_years)

    print(f"\nSelected Listener: {chosen_user['label']}")
    print(f"Available Years:   {', '.join(str(y) for y in avail_years)}")
    yr_choice = input(f"Enter year [default: {latest_year}]: ").strip()

    chosen_year = latest_year
    if yr_choice and yr_choice.isdigit() and int(yr_choice) in avail_years:
        chosen_year = int(yr_choice)

    return chosen_user["user_id"], chosen_year, chosen_user["label"]


def main():
    parser = argparse.ArgumentParser(
        description="Feed Medallion Lakehouse Gold data directly to Mixtape_Wrapped_storyboard.html",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__
    )
    parser.add_argument("-u", "--user", help="User ID (e.g. user_real_01, user_real_02, user_synth_001)")
    parser.add_argument("-y", "--year", type=int, help="Year to load (e.g. 2026, 2025, 2024)")
    parser.add_argument("-l", "--list", action="store_true", help="List all available users and years")
    parser.add_argument("-r", "--rebuild", action="store_true", help="Rebuild local gold marts first")
    parser.add_argument("-n", "--no-open", action="store_true", help="Do not open browser after feeding")
    parser.add_argument("-s", "--serve", action="store_true", help="Serve via local HTTP server")
    parser.add_argument("-p", "--port", type=int, default=8080, help="Port for local HTTP server (default: 8080)")

    args = parser.parse_args()

    # Rebuild gold tables if requested
    if args.rebuild:
        ensure_gold_exists(rebuild=True)

    catalog, users_meta = load_wrapped_catalog()

    # Handle --list
    if args.list:
        print("\n" + "=" * 60)
        print("  AVAILABLE USERS & YEARS IN LAKEHOUSE GOLD LAYER")
        print("=" * 60)
        for u in users_meta:
            yrs_str = ", ".join(str(y) for y in u["years"])
            tag = "[REAL]" if u["is_real"] else "[SYNTH]"
            print(f"  {tag:<7} {u['user_id']:<16} {yrs_str:<25} {u['label']}")
        print(f"\nTotal: {len(users_meta)} users, {sum(len(u['years']) for u in users_meta)} payloads.\n")
        return

    # Determine user & year
    if args.user and args.year:
        user_id = args.user.strip()
        year = args.year
        meta_match = [u for u in users_meta if u["user_id"] == user_id]
        meta_label = meta_match[0]["label"] if meta_match else user_id
    elif args.user and not args.year:
        user_id = args.user.strip()
        meta_match = [u for u in users_meta if u["user_id"] == user_id]
        if meta_match:
            year = max(meta_match[0]["years"])
            meta_label = meta_match[0]["label"]
        else:
            year = 2026
            meta_label = user_id
    else:
        # Interactive mode
        user_id, year, meta_label = interactive_select(users_meta)

    # Validate that payload exists
    if user_id not in catalog or year not in catalog[user_id]:
        print(f"[!] Warning: Payload for {user_id} ({year}) not found in catalog!")
        if user_id in catalog:
            print(f"    Available years for {user_id}: {list(catalog[user_id].keys())}")
        sys.exit(1)

    payload = catalog[user_id][year]

    # 1. Update gold_export/wrapped_bundle.js
    update_bundle_js(catalog, users_meta)

    # 2. Feed directly into Mixtape_Wrapped_storyboard.html
    feed_to_html(user_id, year, payload)

    # 3. Print ASCII cassette summary card
    print_banner(user_id, year, payload, meta_label)

    # 4. Launch browser or start server
    if args.serve:
        serve_and_open(user_id, year, port=args.port)
    elif not args.no_open:
        file_url = HTML_FILE.as_uri() + f"?user={user_id}&year={year}"
        print(f"[*] Opening in default browser:\n    {file_url}\n")
        webbrowser.open(file_url)


if __name__ == "__main__":
    main()
